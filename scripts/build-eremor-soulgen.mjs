import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {eremorClips} from '../tools/soulgen-studio/eremor.mjs';
import {validate,exportPlan} from '../tools/soulgen-studio/model.mjs';

const root=new URL('../art/soulgen/keys/eremor/',import.meta.url);
const report=JSON.parse(await fs.readFile(new URL('parts-report.json',root),'utf8'));
// Rects and pivots share a 340x280 logical stage; PNG proportions remain intact.
const geometry={
 body:{name:'Tronco e patas traseiras',rect:[87,103,184],pivot:[169,173],z:3,parent:null},
 head:{name:'Cabeça e pescoço',rect:[69,80,76],pivot:[131.32,128.53],z:5,parent:'body'},
 armNear:{name:'Braço próximo e garras',rect:[53,117,127],pivot:[162.855,132.974],z:6,parent:'body'},
 armFar:{name:'Braço distante e garras',rect:[16,123,100],pivot:[100,132.843],z:2,parent:'body'},
 sails:{name:'Leque dorsal de velas',rect:[34,45,228],pivot:[143.44,147.125],z:1,parent:'body',lag:.035},
 tail:{name:'Rabiola bifurcada',rect:[247,135,66],pivot:[253.6,176.173],z:0,parent:'body',lag:.12},
 knot:{name:'Nó do Elo e tirantes',rect:[78,118,50],pivot:[103,138.177],z:4,parent:'body'}
};
const project={schema:'soulgen-studio',version:1,name:'Eremor · Elo das Ruínas · rig v3',artRevision:3,width:340,height:280,rootPivot:[157,177],brief:{species:'Eremor — besta ancestral inspirada na preguiça-gigante',personality:'Guardião antigo, pesado e vigilante',kiteAnatomy:'Cinco velas dorsais conectadas, braços de papel com garras-varetas, nó do Elo e rabiola bifurcada',view:'Três quartos voltado à esquerda',reference:'art/concepts/eremor-v1/eremor.png',notes:'Rig colorido derivado do conceito aprovado. Sete peças, cinco ações. Expressões registradas de golpe, dano e vitória; contorno e alpha da cabeça invariantes. Não altera catálogo, aquisição ou atributos.'},assets:{},parts:[],clips:eremorClips()};
for(const [id,p]of Object.entries(geometry)){
 const [width,height]=report.parts[id].size;
 project.assets[id]={name:p.name,src:'/art/soulgen/keys/eremor/parts/'+id+'.png',width,height};
 project.parts.push({id,...p,asset:id,source:[0,0,width,height],rect:[...p.rect,p.rect[2]*height/width],visible:true});
}
const facial=JSON.parse(await fs.readFile(new URL('face-validation-v3.json',root),'utf8'));
const head=project.parts.find(p=>p.id==='head');head.faces={};head.faceWindows=facial.windows;
for(const [face,id]of [['fierce','headFierce'],['hurt','headHurt'],['happy','headHappy']]){
 const [width,height]=facial.canonicalSize;
 project.assets[id]={name:'Cabeça · '+face,src:'/art/soulgen/keys/eremor/parts/'+id+'.png',width,height};
 head.faces[face]={asset:id,source:[0,0,width,height]};
}
// Anatomical landmarks are measured on the source art, independently of the pivots.
// Changing size/position later can therefore be detected by the studio audit.
project.anatomy={version:1,reference:'art/concepts/eremor-v1/eremor.png',
 ratios:[{part:'head',relativeTo:'body',min:.36,max:.46,label:'Cabeça / tronco (largura)'}],
 behind:[{part:'sails',other:'body'},{part:'armFar',other:'body'},{part:'tail',other:'body'},{part:'knot',other:'armNear'}],
 joints:[
  {part:'head',parent:'body',anchor:[.82,.8],socket:[.24087,.21153],maxGap:5},
  {part:'armNear',parent:'body',anchor:[.865,.14],socket:[.41226,.24867],maxGap:5},
  {part:'armFar',parent:'body',anchor:[.84,.10],socket:[.07065,.24736],maxGap:5},
  {part:'sails',parent:'body',anchor:[.48,.80],socket:[.30674,.36567],maxGap:5},
  {part:'tail',parent:'body',anchor:[.10,.71],socket:[.90543,.60640],maxGap:5},
  {part:'knot',parent:'body',anchor:[.5,.63],socket:[.0869565,.291503],maxGap:5}
 ]};
const check=validate(project);if(!check.ok)throw Error(check.errors.join('\n'));
await fs.writeFile(new URL('rig-data.mjs',root),'// Generated by scripts/build-eremor-soulgen.mjs. Source PNGs are preserved.\nexport const project='+JSON.stringify(project,null,2)+';\n');
const embedded=JSON.parse(JSON.stringify(project));
for(const [id,a]of Object.entries(embedded.assets))a.src='data:image/png;base64,'+(await fs.readFile(new URL('parts/'+id+'.png',root))).toString('base64');
if(!validate(embedded).ok)throw Error('Projeto incorporado inválido.');
await fs.writeFile(new URL('eremor.soulgen.json',root),JSON.stringify(embedded));
await fs.writeFile(new URL('eremor-v3.soulgen.json',root),JSON.stringify(embedded));
await fs.writeFile(new URL('export-plan.json',root),JSON.stringify(exportPlan(project,{fps:12,cell:256,columns:8}),null,2)+'\n');
console.log('Eremor: 7 peças, 5 ações e projeto portátil gerados em '+fileURLToPath(root));
